// Step 5: Verify triggers exist
async function verifyTriggers() {
  console.log('');
  console.log('Step 5: Verifying append-only triggers...');
  
  const client = new Client({
    host: DEV_CONFIG.DB_HOST,
    port: parseInt(DEV_CONFIG.DB_PORT),
    user: DEV_CONFIG.DB_USER,
    password: DEV_CONFIG.DB_PASSWORD,
    database: DEV_CONFIG.DB_NAME,
  });

  await client.connect();

  const triggerQuery = `
    SELECT trigger_name, event_manipulation, event_object_table
    FROM information_schema.triggers
    WHERE trigger_schema = 'public'
    ORDER BY event_object_table, trigger_name;
  `;

  const result = await client.query(triggerQuery);
  
  if (result.rows.length > 0) {
    console.log('   Found triggers:');
    for (const row of result.rows) {
      console.log(`   - ${row.trigger_name} (${row.event_manipulation} on ${row.event_object_table})`);
    }
  } else {
    console.log('   ⚠️  No triggers found (append-only enforcement may not be active)');
  }

  await client.end();
}

