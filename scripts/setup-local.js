// Step 2: Check PostgreSQL connection
console.log('');
console.log('Step 2: Checking PostgreSQL connection...');

async function checkPostgres() {
  const client = new Client({
    host: DEV_CONFIG.DB_HOST,
    port: parseInt(DEV_CONFIG.DB_PORT),
    user: DEV_CONFIG.DB_USER,
    password: DEV_CONFIG.DB_PASSWORD,
    database: 'postgres', // Connect to default database first
  });

  try {
    await client.connect();
    console.log('✅ PostgreSQL connection successful');
    
    // Check if database exists
    const result = await client.query(
      "SELECT 1 FROM pg_database WHERE datname = $1",
      [DEV_CONFIG.DB_NAME]
    );
    
    if (result.rows.length === 0) {
      console.log(`   Creating database: ${DEV_CONFIG.DB_NAME}...`);
      await client.query(`CREATE DATABASE ${DEV_CONFIG.DB_NAME}`);
      console.log('✅ Database created');
    } else {
      console.log(`✅ Database ${DEV_CONFIG.DB_NAME} exists`);
    }
    
    await client.end();
    return true;
  } catch (err) {
    console.log('❌ PostgreSQL connection failed:', err.message);
    console.log('');
    console.log('Please ensure PostgreSQL is running and accessible.');
    console.log('You can start PostgreSQL using Docker:');
    console.log('');
    console.log('  docker run -d --name trust-census-postgres \\');
    console.log('    -e POSTGRES_PASSWORD=postgres \\');
    console.log('    -p 5432:5432 \\');
    console.log('    postgres:16-alpine');
    console.log('');
    return false;
  }
}

// Step 3: Run migrations
async function runMigrations() {
  console.log('');
  console.log('Step 3: Running database migrations...');
  
  const client = new Client({
    host: DEV_CONFIG.DB_HOST,
    port: parseInt(DEV_CONFIG.DB_PORT),
    user: DEV_CONFIG.DB_USER,
    password: DEV_CONFIG.DB_PASSWORD,
    database: DEV_CONFIG.DB_NAME,
  });

  await client.connect();

  const migrations = [
    '001_update_roles.sql',
    '002_database_roles.sql',
    '003_user_scopes.sql',
    '004_consent_model.sql',
    '005_micro_aggregates_schema.sql',
    '006_macro_aggregates_schema.sql',
  ];

  for (const migration of migrations) {
    const migrationPath = join(projectRoot, 'src', 'db', 'migrations', migration);
    
    if (!existsSync(migrationPath)) {
      console.log(`⚠️  Migration not found: ${migration}`);
      continue;
    }

    console.log(`   Running ${migration}...`);
    
    try {
      const sql = readFileSync(migrationPath, 'utf-8');
      await client.query(sql);
      console.log(`   ✅ ${migration} completed`);
    } catch (err) {
      // Some errors are expected (e.g., "role already exists")
      if (err.message.includes('already exists') || err.message.includes('duplicate')) {
        console.log(`   ⚠️  ${migration}: ${err.message.split('\n')[0]}`);
      } else {
        console.log(`   ❌ ${migration} failed: ${err.message}`);
      }
    }
  }

  await client.end();
  console.log('✅ Migrations complete');
}

